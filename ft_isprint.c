unsigned int    ft_isprint(char *str)
{
    size_t    i;

    i = 0;
    if (str[i] == '\0')
        return (1);
    while (str[i] != '\0')
    {
        if (str[i] >= ' ' && str[i] <= '~')
            i++;
        else
            return (0);
    }
    return (1);
}