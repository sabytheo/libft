#include "libft.h"

char    ft_tolower(char* str)
{
    size_t i;

    i = 0;

    while (str[i])
    {
        if (str[i] >= 'a' && str[i] <= 'z')
            str[i] = str[i] - 32 ;
        i++;
    }
    return (str); 
}